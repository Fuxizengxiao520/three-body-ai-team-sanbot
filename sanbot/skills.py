def _alias_for(role_id: str, roster: list[str]) -> str:
    for candidate in ROLE_ALIAS_IDS.get(role_id, (role_id,)):
        if candidate in roster:
            return ROLE_NAMES[candidate]
    return ROLE_NAMES.get(roster[-1], "在岗同事") if roster else "在岗同事"


def _fit_to_roster(text: str, roster: list[str] | None, next_name: str | None = None) -> str:
    """把按七人编制写死的样例文案，适配到当前在编名单，杜绝「幽灵同事」。"""
    roster = roster if roster is not None else list(ROLE_NAMES)
    size = len(roster)
    cn = CN_NUM.get(size, str(size))

    for old, new in _DOWNSTREAM_PHRASES.items():
        text = text.replace(old, new)

    present = {ROLE_NAMES[rid] for rid in roster if rid in ROLE_NAMES}
    mapping = {
        name: _alias_for(rid, roster)
        for rid, name in ROLE_NAMES.items()
        if name not in present
    }
    if mapping:
        pattern = "|".join(re.escape(k) for k in sorted(mapping, key=len, reverse=True))
        text = re.sub(pattern, lambda m: mapping[m.group(0)], text)

    if size != 7:
        text = re.sub(r"七(?=个|位|人|棒|名|条|份|气泡|工具|岗位)", cn, text)
        text = re.sub(r"(?<!\d)7(?=\s*个岗位|\s*个\s*AI|\s*人团队)", str(size), text)

    if next_name:
        if "无" in next_name or "终点" in next_name:
            text = re.sub(r"交付人：(.+?) · 下一棒：.+", r"交付人：\1 · 终审（本棒收口）", text)
        else:
            text = re.sub(r"(交付人：.+? · )?下一棒：.+",
                          lambda m: (m.group(1) or "") + f"下一棒：{next_name}", text)
    return text


def _seed(text: str) -> int:
    return int(hashlib.md5(text.encode("utf-8")).hexdigest()[:6], 16)


def _score(brief: str, base: int) -> int:
    return min(96, base + _seed(brief) % 9)


