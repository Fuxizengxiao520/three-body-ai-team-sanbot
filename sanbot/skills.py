def mock_actions(topic: str, roster: list[str] | None = None) -> list[dict]:
    """行动项的责任人必须落在当前在编名单里。"""
    items = [dict(x) for x in MOCK_ACTIONS[_topic_kind(topic)]]
    if not roster:
        return items
    load = {mid: 0 for mid in roster}
    for idx, item in enumerate(items):
        owner = item["owner"]
        if owner in roster:
            chosen = owner
        else:
            chosen = next((c for c in ROLE_ALIAS_IDS.get(owner, (owner,))
                           if c in roster and load[c] < 2), None)
            if chosen is None:
                chosen = min(roster, key=lambda m: (load[m], idx))
        item["owner"] = chosen
        load[chosen] += 1
    return items


